"""PLAN 3.1-3.3: self-training rounds.

Round r (r = 1..max_rounds):
  1. Teacher inference over the ORIGINAL pseudo-labeled pool (teacher = p2_best for round 1,
     then the previous round's model), with its fitted temperature and K = 3 permutations
     -> <teacher_run>/pool/preds.npz and preds.jsonl.  (3.1)
  2. Relabel keep/flip/drop -> data/manifests/train_round{r}.jsonl and
     data/cache/soft_targets_round{r}.npz.  (3.2)
  3. Write configs/exp/p3_round{r}.yaml (inherits the Phase 2 config, swaps the data, loss
     soft_kl) and train it. Each round starts from the AudioJev checkpoint, never from the
     teacher.  (3.3)
  4. Stop if the dev-UA gain over the teacher is below --min_gain (0.5 points).

    python scripts/p3_selftrain.py --teacher_run runs/p2_best/1 --base_config configs/exp/p2_best.yaml

A summary (dev UA per round) is written to runs/p3_selftrain_summary.json. Rounds whose
outputs already exist are not recomputed, so the script can be resumed.
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


def sh(cmd: list[str]) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, cwd=ROOT)


def best_dev_ua(run: Path) -> float:
    return json.loads((run / "results.json").read_text())["best_dev_ua"]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--teacher_run", required=True, help="trained Phase 2 run dir (config.yaml, best/, results.json)")
    ap.add_argument("--base_config", required=True, help="the Phase 2 experiment yaml the rounds inherit")
    ap.add_argument("--pool", default=None, help="original pool manifest (default: data.train_manifest)")
    ap.add_argument("--max_rounds", type=int, default=2)
    ap.add_argument("--min_gain", type=float, default=0.005, help="dev-UA gain (fraction) to start another round")
    ap.add_argument("--tta", type=int, default=3)
    ap.add_argument("--alpha", type=float, default=0.5)
    ap.add_argument("--tau_flip", type=float, default=0.9)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--keep_last", type=int, default=5, help="checkpoints kept per round, for averaging (3.4)")
    args = ap.parse_args()
    os.chdir(ROOT)

    from sersys.config import load_config
    from sersys.prompts import load_label_space
    from sersys.relabel import run as relabel_run

    base = load_config(args.base_config)
    classes = load_label_space(base["labels"], "en").classes
    pool = args.pool or base["data"]["train_manifest"]
    teacher = Path(args.teacher_run)
    summary = {"rounds": [], "teacher_run": str(teacher), "teacher_dev_ua": best_dev_ua(teacher)}
    print(f"round 0 (teacher {teacher}): dev UA {summary['teacher_dev_ua']:.4f}")

    for r in range(1, args.max_rounds + 1):
        pool_dir = teacher / "pool"
        if not (pool_dir / "preds.npz").is_file():
            sh([sys.executable, "-m", "sersys.predict", "--config", str(teacher / "config.yaml"),
                "--adapter", str(teacher / "best"), "--manifest", pool, "--tta", str(args.tta),
                "--out", str(pool_dir)])
        manifest = Path(f"data/manifests/train_round{r}.jsonl")
        targets = Path(f"data/cache/soft_targets_round{r}.npz")
        stats = relabel_run(pool, pool_dir / "preds.npz", r, classes, args.alpha, args.tau_flip,
                            out_manifest=manifest, out_targets=targets)

        exp_name = f"p3_round{r}"
        cfg_path = Path(f"configs/exp/{exp_name}.yaml")
        cfg = {"inherit": args.base_config, "exp_name": exp_name,
               "data": {"train_manifest": str(manifest)},
               "loss": {"type": "soft_kl", "soft_targets": str(targets)},
               "eval": {"keep_last": args.keep_last}}
        cfg_path.write_text(f"# generated by scripts/p3_selftrain.py (round {r}, teacher {teacher})\n"
                            + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        run = Path(f"runs/{exp_name}/{args.seed}")
        if not (run / "results.json").is_file():
            sh(["accelerate", "launch", "--num_processes", "1", "--mixed_precision", "bf16", "-m", "sersys.train",
                "--config", str(cfg_path), "--seed", str(args.seed)])
        ua, prev = best_dev_ua(run), best_dev_ua(teacher)
        summary["rounds"].append({"round": r, "run": str(run), "dev_ua": ua, "gain": ua - prev,
                                  "relabel": stats["overall"], "warnings": stats["warnings"]})
        print(f"round {r}: dev UA {ua:.4f} (gain {100 * (ua - prev):+.2f} points)")
        Path("runs/p3_selftrain_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
        if ua - prev < args.min_gain:
            print(f"gain below {100 * args.min_gain:.1f} points: stopping")
            break
        teacher = run
    best = max([{"run": summary["teacher_run"], "dev_ua": summary["teacher_dev_ua"]}] + summary["rounds"],
               key=lambda x: x["dev_ua"])
    summary["best"] = best
    Path("runs/p3_selftrain_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"best: {best['run']} (dev UA {best['dev_ua']:.4f})")


if __name__ == "__main__":
    main()
